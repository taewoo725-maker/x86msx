/* mousetest.c - 3.0 PC 마우스 해석과 MSX 마우스 규약 시험 */
#include "../kernel/hidmouse.h"
#include "../src/msx.h"
#include <stdio.h>
#include <string.h>

static int pass, fail;
#define CHECK(c, name) do { if (c) { pass++; printf("PASS %s\n", name); } else { fail++; printf("FAIL %s\n", name); } } while (0)

/* QEMU usb-mouse (5 버튼 + X Y 휠, 보고 번호 없음) */
static const uint8_t qemu_desc[] = { 0x05,0x01,0x09,0x02,0xa1,0x01,0x09,0x01,0xa1,0x00,0x05,0x09,0x19,0x01,0x29,0x05,0x15,0x00,0x25,0x01,
    0x95,0x05,0x75,0x01,0x81,0x02,0x95,0x01,0x75,0x03,0x81,0x01,0x05,0x01,0x09,0x30,0x09,0x31,0x09,0x38,0x15,0x81,0x25,0x7f,
    0x75,0x08,0x95,0x03,0x81,0x06,0xc0,0xc0 };
/* 무선 수신기 흉내: 보고 번호 2, 버튼 16개, X·Y 12비트, 휠 8비트 (앞에 키보드 모음이 있음) */
static const uint8_t rx_desc[] = {
    0x05,0x01,0x09,0x06,0xa1,0x01,0x85,0x01,0x05,0x07,0x19,0xe0,0x29,0xe7,0x15,0x00,0x25,0x01,0x75,0x01,0x95,0x08,0x81,0x02,0xc0,
    0x05,0x01,0x09,0x02,0xa1,0x01,0x85,0x02,0x09,0x01,0xa1,0x00,0x05,0x09,0x19,0x01,0x29,0x10,0x15,0x00,0x25,0x01,0x95,0x10,0x75,0x01,0x81,0x02,
    0x05,0x01,0x16,0x01,0xf8,0x26,0xff,0x07,0x75,0x0c,0x95,0x02,0x09,0x30,0x09,0x31,0x81,0x06,
    0x15,0x81,0x25,0x7f,0x75,0x08,0x95,0x01,0x09,0x38,0x81,0x06,0xc0,0xc0 };
/* 태블릿 (절대값): 마우스로 보지 않음 */
static const uint8_t tab_desc[] = { 0x05,0x01,0x09,0x02,0xa1,0x01,0x09,0x01,0xa1,0x00,0x05,0x09,0x19,0x01,0x29,0x03,0x15,0x00,0x25,0x01,
    0x95,0x03,0x75,0x01,0x81,0x02,0x95,0x01,0x75,0x05,0x81,0x01,0x05,0x01,0x09,0x30,0x09,0x31,0x15,0x00,0x26,0xff,0x7f,0x75,0x10,0x95,0x02,0x81,0x02,0xc0,0xc0 };

int main(void)
{
    HidMouse m;
    int dx, dy, dz, b;
    CHECK(!hidmouse_parse(&m, qemu_desc, sizeof qemu_desc), "qemu descriptor is a mouse");
    { uint8_t r[4] = { 0x05, 0xFB, 0x07, 0x01 }; CHECK(!hidmouse_decode(&m, r, 4, &dx, &dy, &dz, &b) && dx == -5 && dy == 7 && dz == 1 && b == 5, "qemu report"); }
    CHECK(!hidmouse_parse(&m, rx_desc, sizeof rx_desc) && m.report_id == 2, "receiver mouse collection, report id 2");
    {   /* 버튼 1(왼쪽), X = -3 (12비트), Y = +300, 휠 -1 */
        uint8_t r[7] = { 2, 0x01, 0x00, 0, 0, 0, 0xFF };
        int x = -3 & 0xFFF, y = 300;
        r[3] = (uint8_t)(x & 0xFF); r[4] = (uint8_t)((x >> 8) | ((y & 0x0F) << 4)); r[5] = (uint8_t)(y >> 4);
        CHECK(!hidmouse_decode(&m, r, 7, &dx, &dy, &dz, &b) && dx == -3 && dy == 300 && dz == -1 && b == 1, "receiver 12-bit report");
        r[0] = 1;
        CHECK(hidmouse_decode(&m, r, 7, &dx, &dy, &dz, &b) != 0, "other report id ignored");
    }
    CHECK(hidmouse_parse(&m, tab_desc, sizeof tab_desc) != 0, "absolute tablet is not a mouse");
    hidmouse_boot(&m);
    { uint8_t r[3] = { 0x02, 0x10, 0xF0 }; CHECK(!hidmouse_decode(&m, r, 3, &dx, &dy, &dz, &b) && dx == 16 && dy == -16 && b == 2, "boot protocol"); }

    Ps2Mouse p = { .size = 4 };
    int got = 0;
    uint8_t pk[] = { 0x00, 0x29, 0x05, 0xFE, 0x01 };           /* 앞의 0x00은 맞추기로 버림. 왼쪽, X +5, Y -2(PS/2) → +2, 휠 +1(아래) */
    for (unsigned i = 0; i < sizeof pk; i++) got |= ps2mouse_byte(&p, pk[i], &dx, &dy, &dz, &b);
    CHECK(got && dx == 5 && dy == 2 && dz == -1 && b == 1, "ps/2 4-byte packet");

    /* MSX 마우스: 핀 8을 바꿀 때마다 X 위 4비트, X 아래, Y 위, Y 아래 */
    static MSX msx;
    memset(&msx, 0, sizeof msx);
    msx.mouse_port = 0;
    msx.mouse_cx = 0x35; msx.mouse_cy = -2;
    msx.mouse_btn = 1;
    uint8_t want[4] = { 0x3, 0x5, 0xF, 0xE }, ok = 1, pin = 0;
    msx.cpu.cycles = 100000;
    msx.mouse_t = 0;
    for (int k = 0; k < 4; k++) {
        pin ^= 0x10;
        msx_io_write(&msx, 0xA0, 15); msx_io_write(&msx, 0xA1, pin);
        msx.cpu.cycles += 100;
        msx_io_write(&msx, 0xA0, 14);
        uint8_t v = msx_io_read(&msx, 0xA2);
        if ((v & 0x0F) != want[k] || (v & 0x30) != 0x20) ok = 0;
    }
    CHECK(ok, "msx mouse nibbles and buttons");
    CHECK(msx.mouse_cx == 0 && msx.mouse_cy == 0, "msx mouse movement consumed");
    printf("mousetest: %d/%d passed\n", pass, pass + fail);
    return fail != 0;
}
