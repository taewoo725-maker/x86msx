/* hidpadtest.c - USB 게임패드 보고 해석 시험 (2.13) */
#include "../kernel/hidpad.h"
#include <stdio.h>

static int fails;
static void check(const char *what, int got, int want)
{
    int ok = got == want;
    printf("%s %-46s got %02X want %02X\n", ok ? "PASS" : "FAIL", what, got & 0xFF, want & 0xFF);
    if (!ok) fails++;
}

/* 흔한 값싼 USB 조이패드 (DragonRise 0079:0006): 축 5개 8비트 0~255, hat 4비트 0~7, 버튼 12개 */
static const uint8_t dragonrise[] = {
    0x05,0x01, 0x09,0x04, 0xA1,0x01, 0xA1,0x02,
    0x75,0x08, 0x95,0x05, 0x15,0x00, 0x26,0xFF,0x00, 0x35,0x00, 0x46,0xFF,0x00,
    0x09,0x30, 0x09,0x31, 0x09,0x32, 0x09,0x32, 0x09,0x35, 0x81,0x02,
    0x75,0x04, 0x95,0x01, 0x25,0x07, 0x46,0x3B,0x01, 0x65,0x14, 0x09,0x39, 0x81,0x42,
    0x65,0x00, 0x75,0x01, 0x95,0x0C, 0x25,0x01, 0x45,0x01, 0x05,0x09, 0x19,0x01, 0x29,0x0C, 0x81,0x02,
    0x06,0x00,0xFF, 0x75,0x01, 0x95,0x08, 0x25,0x01, 0x45,0x01, 0x09,0x01, 0x81,0x02,
    0xC0, 0xC0,
};
/* 보고 번호가 있는 게임패드 (번호 1): 버튼 8개 먼저, X·Y 부호 있는 8비트 */
static const uint8_t with_id[] = {
    0x05,0x01, 0x09,0x05, 0xA1,0x01, 0x85,0x01,
    0x05,0x09, 0x19,0x01, 0x29,0x08, 0x15,0x00, 0x25,0x01, 0x75,0x01, 0x95,0x08, 0x81,0x02,
    0x05,0x01, 0x09,0x30, 0x09,0x31, 0x15,0x81, 0x25,0x7F, 0x75,0x08, 0x95,0x02, 0x81,0x02,
    0xC0,
};
/* 마우스는 게임패드가 아님 */
static const uint8_t mouse[] = {
    0x05,0x01, 0x09,0x02, 0xA1,0x01, 0x09,0x01, 0xA1,0x00, 0x05,0x09, 0x19,0x01, 0x29,0x03,
    0x15,0x00, 0x25,0x01, 0x95,0x03, 0x75,0x01, 0x81,0x02, 0x95,0x01, 0x75,0x05, 0x81,0x01,
    0x05,0x01, 0x09,0x30, 0x09,0x31, 0x15,0x81, 0x25,0x7F, 0x75,0x08, 0x95,0x02, 0x81,0x06, 0xC0, 0xC0,
};

int main(void)
{
    HidPad p;
    check("dragonrise parse", hidpad_parse(dragonrise, sizeof dragonrise, &p), 1);
    {   /* X Y Z Rz Rz, hat|buttons(4비트+4비트), 버튼 8비트, 벤더 8비트 */
        uint8_t c[8] = { 0x7F, 0x7F, 0x7F, 0x7F, 0x7F, 0x0F, 0x00, 0x00 };
        check("dragonrise centre", hidpad_decode(&p, c, 8), 0);
        uint8_t l[8] = { 0x00, 0x7F, 0x7F, 0x7F, 0x7F, 0x0F, 0x00, 0x00 };
        check("dragonrise left", hidpad_decode(&p, l, 8), PAD_LEFT);
        uint8_t u[8] = { 0x7F, 0x00, 0x7F, 0x7F, 0x7F, 0x0F, 0x00, 0x00 };
        check("dragonrise up", hidpad_decode(&p, u, 8), PAD_UP);
        uint8_t h[8] = { 0x7F, 0x7F, 0x7F, 0x7F, 0x7F, 0x13, 0x00, 0x00 };   /* hat 3 = 오른쪽 아래, 버튼 1 */
        check("dragonrise hat down-right + button1", hidpad_decode(&p, h, 8), PAD_RIGHT | PAD_DOWN | PAD_A);
        uint8_t b[8] = { 0x7F, 0x7F, 0x7F, 0x7F, 0x7F, 0x2F, 0x20, 0x00 };   /* 버튼 2, 버튼 10 */
        check("dragonrise button2 + start(10)", hidpad_decode(&p, b, 8), PAD_B | PAD_START);
        PadView v;   /* 3.8.1 진단 조이스틱 시험: 축 원값·방향 스위치·버튼 비트 */
        check("view ok", hidpad_view(&p, h, 8, &v), 0);
        check("view x raw", v.x, 0x7F); check("view hat down-right", v.hat, 3); check("view button1", (int)(v.btn & 1), 1);
        check("view button2 off", (int)((v.btn >> 1) & 1), 0);
        hidpad_view(&p, b, 8, &v);
        check("view button2+10", (int)(v.btn & 0x202), 0x202); check("view hat centre", v.hat, -1);
    }
    check("report-id pad parse", hidpad_parse(with_id, sizeof with_id, &p), 1);
    {
        uint8_t r[4] = { 0x01, 0x01, 0x81, 0x7F };  /* 버튼 1, X 최소, Y 최대 */
        check("report-id pad left-down + A", hidpad_decode(&p, r, 4), PAD_LEFT | PAD_DOWN | PAD_A);
        uint8_t o[4] = { 0x02, 0x01, 0x81, 0x7F };
        check("other report id ignored", hidpad_decode(&p, o, 4), -1);
    }
    check("mouse is not a pad", hidpad_parse(mouse, sizeof mouse, &p), 0);
    hidpad_xinput(&p);
    {
        uint8_t x[20] = { 0x00, 0x14, 0x01 | 0x10, 0x10, 0, 0, 0x00, 0x80, 0, 0 };  /* 위 + Start + A, LX 최소 */
        check("xbox360 up+start+A, stick left", hidpad_decode(&p, x, 20), PAD_UP | PAD_START | PAD_A | PAD_LEFT);
        PadView v;
        hidpad_view(&p, x, 20, &v);
        check("view xbox hat up", v.hat, 0); check("view xbox stick x", v.x, -32768);
    }
    printf("hidpadtest: %s\n", fails ? "FAILED" : "all passed");
    return fails ? 1 : 0;
}
